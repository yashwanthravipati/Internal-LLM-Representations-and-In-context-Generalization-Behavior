"""T-016: summarize the behavioral pilot (validation split only).

Collects every results/*_pilot_* run, joins behavior with prompts, and writes
results/pilot/REPORT.md plus figures in results/pilot/.

    uv run python scripts/analyze_pilot.py
"""

from __future__ import annotations

import json

import numpy as np
import pandas as pd

from icl_geometry import io
from icl_geometry.analysis.exp1 import llm_task_errors
from icl_geometry.plotting import INK_MUTED, SERIES, apply_style, plt, save

OUT = io.REPO_ROOT / "results" / "pilot"


def load_runs() -> pd.DataFrame:
    frames = []
    for d in sorted(io.RESULTS_DIR.glob("*_pilot_*")):
        if not (d / "behavior.parquet").exists():
            continue
        cfg = io.RunConfig.from_yaml(d / "config.yaml")
        beh = pd.read_parquet(d / "behavior.parquet")
        prompts = pd.DataFrame(io.read_jsonl(io.REPO_ROOT / cfg.prompt_set))
        df = beh.merge(prompts, on="prompt_id")
        df["model_short"] = io.model_short_name(cfg.model)
        df["run"] = d.name
        frames.append(df)
    if not frames:
        raise SystemExit("no pilot runs found")
    df = pd.concat(frames, ignore_index=True)
    # Keep the latest run per (model, prompt set) if a set was re-run.
    latest = df.groupby(["model_short", "template_id", "experiment"]).run.transform("max")
    return df[df.run == latest]


def acc_table(df, by):
    g = df.groupby(by)
    out = g.agg(acc=("correct", "mean"), n=("correct", "size"),
                label_mass=("label_mass", "median"))
    if "correct_calibrated" in df:
        out["acc_cal"] = g.correct_calibrated.mean()
    return out.round(3)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    df = load_runs()
    apply_style()
    lines = ["# Behavioral pilot (T-016)", "",
             "_Validation split only. Generated by `scripts/analyze_pilot.py`._", "",
             "Runs: " + ", ".join(f"`{r}`" for r in sorted(df.run.unique())), ""]
    models = sorted(df.model_short.unique())

    # ---------------- Exp 2 ----------------
    e2 = df[df.experiment == "exp2"].copy()
    e2["query_type"] = np.where(e2.congruent, "congruent", "incongruent")
    lines += ["## Experiment 2", "",
              "### Accuracy by model, template, condition, query type", "",
              acc_table(e2, ["model_short", "template_id", "condition", "query_type"])
              .to_markdown(), ""]
    main_ = e2[e2.condition == "main"]
    lines += ["### Main condition, incongruent queries, by domain x cued attribute x m", "",
              acc_table(main_[~main_.congruent],
                        ["model_short", "template_id", "domain", "cued_attr", "m"])
              .to_markdown(), ""]

    # Figure: incongruent accuracy vs m per domain (arrow template, main), models as series
    domains = sorted(e2.domain.unique())
    fig, axes = plt.subplots(1, len(domains), figsize=(3.2 * len(domains), 3.2), sharey=True)
    for ax, dom in zip(np.atleast_1d(axes), domains, strict=True):
        for color, model in zip(SERIES, models, strict=False):
            for ls, cued_i in (("-", 0), ("--", 1)):
                sub = main_[(main_.domain == dom) & (main_.model_short == model)
                            & (main_.template_id == "arrow") & ~main_.congruent]
                if sub.empty:
                    continue
                cued = sorted(sub.cued_attr.unique())[cued_i] if sub.cued_attr.nunique() > cued_i \
                    else None
                if cued is None:
                    continue
                g = sub[sub.cued_attr == cued].groupby("m").correct.mean()
                ax.plot(g.index, g.values, ls=ls, color=color, marker="o", ms=4,
                        label=f"{model}, cue={cued}")
        ax.axhline(0.5, color=INK_MUTED, lw=1, ls=":")
        ax.set(title=dom, xlabel="m (demos per label)", ylim=(0, 1), xticks=[2, 4, 8])
        ax.legend(fontsize=6)
    np.atleast_1d(axes)[0].set_ylabel("Accuracy, incongruent queries")
    fig.suptitle("Exp 2 pilot: learning the demonstrated grouping (arrow template, main)",
                 x=0.01, ha="left")
    fig.tight_layout()
    save(fig, OUT / "exp2_incongruent_vs_m.png")
    lines += ["![Exp 2 incongruent accuracy vs m](exp2_incongruent_vs_m.png)", ""]

    # Figure: condition comparison (incongruent) per model
    fig, ax = plt.subplots(figsize=(6, 3.2))
    conds = ["main", "random_label", "explicit_rule"]
    width = 0.8 / max(len(models), 1)
    for k, (color, model) in enumerate(zip(SERIES, models, strict=False)):
        sub = e2[(e2.model_short == model) & (e2.template_id == "arrow") & ~e2.congruent]
        vals = [sub[sub.condition == c].correct.mean() for c in conds]
        ax.bar(np.arange(len(conds)) + k * width, vals, width * 0.92, color=color, label=model)
    ax.axhline(0.5, color=INK_MUTED, lw=1, ls=":")
    ax.set(xticks=np.arange(len(conds)) + width * (len(models) - 1) / 2, xticklabels=conds,
           ylabel="Accuracy, incongruent", ylim=(0, 1), title="Exp 2 pilot: controls")
    ax.legend()
    save(fig, OUT / "exp2_conditions.png")
    lines += ["![Exp 2 conditions](exp2_conditions.png)", ""]

    # ---------------- Exp 1 ----------------
    e1 = df[df.experiment == "exp1"].copy()
    if not e1.empty:
        lines += ["## Experiment 1", "", "### Accuracy by model, template, m, relatedness", "",
                  acc_table(e1, ["model_short", "template_id", "m", "related"]).to_markdown(),
                  ""]
        fig, axes = plt.subplots(1, 2, figsize=(9, 3.2))
        spread = []
        for color, model in zip(SERIES, models, strict=False):
            for ls, tmpl in (("-", "arrow"), ("--", "io")):
                sub = e1[(e1.model_short == model) & (e1.template_id == tmpl)]
                if sub.empty:
                    continue
                g = sub.groupby("m").correct.mean()
                axes[0].plot(g.index, g.values, ls=ls, color=color, marker="o", ms=4,
                             label=f"{model}, {tmpl}")
                tasks = llm_task_errors(
                    sub[["prompt_id", "category_pair", "query_attrs", "m", "related"]],
                    sub[["prompt_id", "correct", "margin", "label_mass"]
                        + (["correct_calibrated"] if "correct_calibrated" in sub else [])])
                for m, gm in tasks.groupby("m"):
                    spread.append({"model": model, "template": tmpl, "m": m,
                                   "task_error_mean": gm.error.mean(),
                                   "task_error_sd": gm.error.std(),
                                   "frac_tasks_at_0": (gm.error == 0).mean(),
                                   "frac_tasks_ge_0.5": (gm.error >= 0.5).mean(),
                                   "n_tasks": len(gm)})
                if tmpl == "arrow":
                    axes[1].hist(tasks[tasks.m == 2].error, bins=np.linspace(0, 1, 11),
                                 color=color, alpha=0.6, label=f"{model} (m=2)")
        axes[0].set(xscale="log", xticks=[1, 2, 4, 8], xticklabels=["1", "2", "4", "8"],
                    xlabel="m (demos per category)", ylabel="Accuracy", ylim=(0.4, 1),
                    title="Exp 1 learning curves")
        axes[0].legend(fontsize=7)
        axes[1].set(xlabel="Task error (pair x direction)", ylabel="Tasks",
                    title="Spread of task errors (arrow, m = 2)")
        axes[1].legend(fontsize=7)
        fig.tight_layout()
        save(fig, OUT / "exp1_learning_curves.png")
        lines += ["![Exp 1](exp1_learning_curves.png)", "",
                  "### Dynamic range across tasks (pair x direction)", "",
                  pd.DataFrame(spread).round(3).to_markdown(index=False), ""]

    lines += ["## Label mass (format following)", "",
              df.groupby(["model_short", "template_id", "experiment"]).label_mass
              .describe()[["25%", "50%", "75%"]].round(3).to_markdown(), ""]
    (OUT / "REPORT.md").write_text("\n".join(lines) + "\n")
    summary = {
        "exp2_incongruent_main": acc_table(main_[~main_.congruent],
                                           ["model_short", "template_id"]).acc.to_dict(),
    }
    (OUT / "summary.json").write_text(json.dumps({str(k): v for k, v in
                                                  summary["exp2_incongruent_main"].items()},
                                                 indent=2))
    print("\n".join(lines[:60]))


if __name__ == "__main__":
    main()
