"""T-011: validate the item banks and write results/item_bank_report.md.

Checks: required columns, empty fields, duplicates within and across files, counts per
category / crossed cell (all items and high-confidence only), balance across crossed cells.
Exits non-zero on hard failures (missing columns, empty items, within-file duplicates).

    uv run python scripts/validate_items.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
REQUIRED = ["item", "source", "confidence"]


def main() -> int:
    domains = yaml.safe_load((ROOT / "configs" / "domains.yaml").read_text())
    errors: list[str] = []
    lines = ["# Item bank report", "", "_Generated by `scripts/validate_items.py`._", ""]

    cat = pd.read_csv(ROOT / domains["exp1"]["items"])
    for col in REQUIRED + ["category", "superordinate"]:
        if col not in cat:
            errors.append(f"categories.csv: missing column {col}")
    dup = cat[cat.item.duplicated()]
    if len(dup):
        errors.append(f"categories.csv: duplicate items {list(dup.item)}")
    min_n = domains["exp1"]["min_items_per_category"]
    counts = cat.groupby(["superordinate", "category"]).agg(
        n=("item", "size"), high=("confidence", lambda s: int((s == "high").sum()))
    ).reset_index()
    lines += [
        "## Experiment 1: categories", "",
        f"{len(cat)} items, {cat.category.nunique()} categories, "
        f"{cat.superordinate.nunique()} superordinates. Target: >= {min_n} usable items per "
        f"category after model filtering (~30% headroom before filtering => ~{int(min_n * 1.3)}).",
        "",
        "| Superordinate | Category | Items | High confidence | Flag |",
        "|---|---|---|---|---|",
    ]
    for r in counts.itertuples():
        flag = "below target" if r.high < int(min_n * 1.3) else ""
        lines.append(f"| {r.superordinate} | {r.category} | {r.n} | {r.high} | {flag} |")
    n_cat = cat.category.nunique()
    sup = cat.groupby("category").superordinate.first()
    pairs = n_cat * (n_cat - 1) // 2
    within = sum(
        len(g) * (len(g) - 1) // 2 for _, g in sup.groupby(sup)
    )
    lines += ["", f"Category pairs: {pairs} ({within} within-superordinate, "
              f"{pairs - within} across).", ""]

    lines += ["## Experiment 2: crossed domains", ""]
    all_items: dict[str, list[str]] = {"categories": list(cat.item)}
    for name, spec in domains["exp2"].items():
        df = pd.read_csv(ROOT / spec["items"])
        attrs = list(spec["attributes"])
        for col in REQUIRED + attrs:
            if col not in df:
                errors.append(f"{name}: missing column {col}")
        if df.item.isna().any() or (df.item.astype(str).str.strip() == "").any():
            errors.append(f"{name}: empty item")
        if df.item.duplicated().any():
            errors.append(f"{name}: duplicate items {list(df.item[df.item.duplicated()])}")
        for a in attrs:
            bad = set(df[a].astype(str)) - set(map(str, spec["attributes"][a]["values"]))
            if bad:
                errors.append(f"{name}: unexpected values for {a}: {bad}")
        all_items[name] = list(df.item.astype(str))
        cells = df.groupby(attrs).agg(
            n=("item", "size"), high=("confidence", lambda s: int((s == "high").sum()))
        ).reset_index()
        lines += [f"### {name}", "", f"| {attrs[0]} | {attrs[1]} | Items | High | Flag |",
                  "|---|---|---|---|---|"]
        for r in cells.itertuples(index=False):
            flag = "below 10" if r.high < 10 else ("below 20" if r.high < 20 else "")
            lines.append(f"| {r[0]} | {r[1]} | {r.n} | {r.high} | {flag} |")
        ratio = cells.high.max() / max(cells.high.min(), 1)
        lines += ["", f"Balance (max/min high-confidence cell): {ratio:.1f}", ""]

    # Cross-file duplicates are allowed (e.g. 'dog' in categories and animals), just reported.
    seen: dict[str, list[str]] = {}
    for name, items in all_items.items():
        for it in items:
            seen.setdefault(it.lower(), []).append(name)
    shared = {k: v for k, v in seen.items() if len(v) > 1}
    lines += ["## Items shared across files", "",
              f"{len(shared)} items appear in more than one bank (allowed; experiments are "
              "analysed separately).", ""]

    lines += ["## Hard checks", ""] + ([f"- FAIL: {e}" for e in errors] or ["- all passed"])
    out = ROOT / "results" / "item_bank_report.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines[-3:]))
    print("wrote", out)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
